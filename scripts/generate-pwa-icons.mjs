import { mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "students/public/assets/Logo1.png");
const portals = ["admins", "mentors", "students"];

async function createIcon(size, markSize, background) {
  const source = await sharp(sourcePath)
    .extract({ left: 0, top: 0, width: 2463, height: 2463 })
    .resize(markSize, markSize, { fit: "contain" })
    .png()
    .toBuffer();

  return sharp({
    create: {
      width: size,
      height: size,
      channels: 4,
      background
    }
  })
    .composite([{ input: source, gravity: "center" }])
    .png({ compressionLevel: 9 })
    .toBuffer();
}

const [icon192, icon512, maskable512] = await Promise.all([
  createIcon(192, 158, "#FFFFFF"),
  createIcon(512, 420, "#FFFFFF"),
  createIcon(512, 310, "#F7F9FC")
]);

for (const portal of portals) {
  const outputDirectory = path.join(root, portal, "public/icons");
  await mkdir(outputDirectory, { recursive: true });
  await Promise.all([
    sharp(icon192).toFile(path.join(outputDirectory, "icon-192.png")),
    sharp(icon512).toFile(path.join(outputDirectory, "icon-512.png")),
    sharp(maskable512).toFile(path.join(outputDirectory, "icon-maskable-512.png"))
  ]);
}

console.log("Generated BYBS PWA icons for admin, mentor, and mentee portals.");
